// Case AST → pytest + playwright-python spec source (casesheet build --lang py).
import { analyzeCase, testTitle, expandTemplate } from "./emit.js";
import { caseVariants } from "./cases.js";
import { RUNTIME_PY, CONFTEST_PY } from "./runtime-py.js";

const pq = (s) => '"' + String(s).replace(/\\/g, "\\\\").replace(/"/g, '\\"').replace(/\r/g, "\\r").replace(/\n/g, "\\n") + '"';
const fpart = (s) => String(s).replace(/\\/g, "\\\\").replace(/"/g, '\\"').replace(/\r/g, "\\r").replace(/\n/g, "\\n").replace(/\{/g, "{{").replace(/\}/g, "}}");

/** Python string literal; `{{VAR}}` becomes an f-string with an environment lookup. */
export function pylit(value) {
  const s = String(value ?? "");
  if (!/\{\{\s*[A-Za-z_][\w.-]*\s*\}\}/.test(s)) return pq(s);
  const parts = s.split(/(\{\{\s*[A-Za-z_][\w.-]*\s*\}\})/g);
  return 'f"' + parts.map((p) => {
    const m = /^\{\{\s*([A-Za-z_][\w.-]*)\s*\}\}$/.exec(p);
    return m ? "{ui.env('" + m[1] + "')}" : fpart(p);
  }).join("") + '"';
}

const kindArg = (kind) => (kind ? ", " + pq(kind) : "");

export function codeForPy(ast, ctx) {
  const routes = ctx.routes || {};
  switch (ast.type) {
    case "goto":
      if (ast.isUrl) return [`page.goto(${pylit(ast.target)})`];
      if (ast.target in routes) return [`page.goto(${pq(routes[ast.target])})`];
      return [`ui.open(page, ${pq(ast.target)})`];
    case "fill":
      return [`ui.fill(page, ${pq(ast.field)}, ${pylit(ast.value)})`];
    case "click": {
      const opts = ast.dbl ? ", click_count=2" : ast.right ? ', button="right"' : "";
      return [`ui.click(page, ${pq(ast.target)}${ast.kind ? kindArg(ast.kind) : opts ? ", None" : ""}${opts})`];
    }
    case "press":
      return [`page.keyboard.press(${pq(ast.key)})`];
    case "select":
      return [`ui.select(page, ${pq(ast.field)}, ${pylit(ast.option)})`];
    case "check":
      return [`ui.check(page, ${pq(ast.label)}, ${ast.checked ? "True" : "False"})`];
    case "hover":
      return [`ui.pick_any(page, ${pq(ast.target)}).hover()`];
    case "upload":
      return [`ui.upload(page, ${ast.field ? pq(ast.field) : "None"}, ${pylit(ast.file)})`];
    case "wait":
      return [`page.wait_for_timeout(${ast.ms})`];
    case "waitVisible":
      return [`expect(ui.text(page, ${pq(ast.text)})).to_be_visible(timeout=15000)`];
    case "reload":
      return ["page.reload()"];
    case "back":
      return ["page.go_back()"];
    case "scroll":
      return [`ui.pick_any(page, ${pq(ast.target)}).scroll_into_view_if_needed()`];
    case "scrollBottom":
      return ['page.evaluate("window.scrollTo(0, document.body.scrollHeight)")'];
    case "screenshot":
      return [`ui.screenshot(page, ${pq(`step-${ctx.stepNo || 0}.png`)})`];
    case "closeDialog":
      return ["ui.close_dialog(page)"];
    case "expectVisible":
      return [`expect(ui.text(page, ${pq(ast.text)}${kindArg(ast.kind)})).to_be_visible()`];
    case "expectHidden":
      return [`expect(ui.text_all(page, ${pq(ast.text)}${kindArg(ast.kind)})).to_have_count(0)`];
    case "expectUrl":
      return [`expect(page).to_have_url(ui.url(${pylit(ast.target)}, ${pq(ast.mode)}))`];
    case "expectTitle":
      return [`expect(page).to_have_title(re.compile(re.escape(${pq(ast.text)})))`];
    case "expectValue":
      return [`expect(ui.pick_field(page, ${pq(ast.field)})).to_have_value(${pylit(ast.value)})`];
    case "expectDisabled":
      return [`expect(ui.pick_any(page, ${pq(ast.target)}${kindArg(ast.kind)})).${ast.disabled ? "to_be_disabled" : "to_be_enabled"}()`];
    case "expectChecked":
      return [`expect(ui.pick_check(page, ${pq(ast.label)})).${ast.checked ? "to_be_checked" : "not_to_be_checked"}()`];
    case "custom":
      return ast.py ? expandTemplate(ast.py, ast.groups, pylit) : null;
    default:
      return null;
  }
}

/** Python identifier from free text: letters and digits are kept (unicode included), the rest becomes "_". */
export function pyIdent(s, { max = 48, lower = true } = {}) {
  let id = String(s).normalize("NFKC").replace(/[^\p{L}\p{N}]+/gu, "_").replace(/^_+|_+$/g, "").slice(0, max).replace(/_+$/, "");
  if (lower) id = id.toLowerCase();
  if (!id) id = "x";
  if (/^\p{N}/u.test(id)) id = "_" + id;
  return id;
}

export function emitSpecPy(cases, cfg, meta) {
  const L = [];
  L.push(`# Generated by casesheet from ${meta.sourceRel}. Do not edit by hand: change the sheet and run \`casesheet build --lang py\` again.`);
  L.push("import re");
  L.push("");
  L.push("import pytest");
  L.push("from playwright.sync_api import Page, expect");
  L.push("");
  L.push("from _casesheet import ui");
  L.push("");
  const groups = new Map();
  for (const c of cases) {
    if (!groups.has(c.module)) groups.set(c.module, []);
    groups.get(c.module).push(c);
  }
  const map = [];
  const stats = { cases: 0, steps: 0, unknownSteps: [], unknownExpect: [], manual: 0, fixme: 0, tags: new Set() };
  const names = new Set();
  const uniq = (n) => {
    let name = n;
    for (let i = 2; names.has(name); i++) name = `${n}_${i}`;
    names.add(name);
    return name;
  };
  for (const [module, list] of groups) {
    L.push("");
    L.push(`# ---- ${module} ----`);
    for (const base of list) {
      const variants = caseVariants(base);
      const entry = { id: base.id, title: base.title, module, source: base.source, line: 0 };
      if (variants.length > 1) entry.variants = [];
      map.push(entry);
      stats.cases++;
      for (const c of variants) {
        const { blocks, unknownSteps, unknownExpect, stepCount } = analyzeCase(c, cfg);
        if (c === variants[0]) {
          stats.steps += stepCount;
          stats.unknownSteps.push(...unknownSteps.map((t) => ({ id: c.id, text: t })));
          stats.unknownExpect.push(...unknownExpect.map((t) => ({ id: c.id, text: t })));
        }
        const tags = [];
        if (c.priority) tags.push(pyIdent(c.priority, { lower: false }));
        for (const t of c.tags) tags.push(pyIdent(t, { lower: false }));
        for (const t of new Set(tags)) stats.tags.add(t);
        const kw = [`id=${pq(c.id)}`, `title=${pq(testTitle(c))}`, `module=${pq(module)}`, `source=${pq(c.source)}`];
        if (c.data) kw.push(`data=${pq(c.data)}`);
        if (c.notes) kw.push(`notes=${pq(c.notes)}`);
        const fname = uniq(`test_${pyIdent(c.id)}_${pyIdent(c.title)}${c.variant ? "_" + c.variant.split("/")[0] : ""}`);
        L.push("");
        L.push("");
        for (const t of new Set(tags)) L.push(`@pytest.mark.${t}`);
        L.push(`@pytest.mark.casesheet(${kw.join(", ")})`);
        const defLine = L.length + 1;
        if (c.variant) entry.variants.push({ data: c.variant, title: c.title, line: defLine });
        if (!entry.line) entry.line = defLine;
        L.push(`def ${fname}(page: Page, record_property):`);
        L.push(`    """${testTitle(c).replace(/"""/g, '"')}"""`);
        const body = [];
        for (const b of blocks.filter((b) => b.kind === "pre")) {
          const code = b.ast.type === "unknown" || b.ast.type === "noop" ? null : codeForPy(b.ast, { routes: cfg.routes });
          body.push(`    # 前置条件 / precondition: ${b.text}`);
          if (code) for (const line of code) body.push("    " + line);
        }
        let lastMacro = null;
        for (const b of blocks) {
          if (b.kind === "pre") continue;
          const code = b.ast.type === "unknown" ? null : codeForPy(b.ast, { routes: cfg.routes, stepNo: b.no });
          const reason = b.ast.type === "custom" && !code ? `custom rule "${b.ast.name}" has no "py" template in casesheet.config.json` : null;
          if (b.kind === "step") {
            if (b.macro && b.macro !== lastMacro) body.push(`    # macro: ${b.macro}`);
            lastMacro = b.macro || null;
            if (!code) {
              stats.fixme++;
              const msg = reason || `unrecognized step: ${b.text}`;
              body.push(`    # casesheet could not turn this step into code. Implement it here, or add a macro / rule in casesheet.config.json.`);
              body.push(cfg.strict ? `    pytest.fail(${pq(msg)})` : `    ui.fixme(record_property, ${pq(msg)})`);
              continue;
            }
            body.push(`    with ui.step(${pq(`${b.label}. ${b.text}`)}):`);
            for (const line of code) body.push("        " + line);
          } else {
            if (!code) {
              const msg = reason || `unrecognized expectation: ${b.text}`;
              if (cfg.strict) {
                stats.fixme++;
                body.push(`    pytest.fail(${pq(msg)})`);
              } else {
                stats.manual++;
                body.push(`    ui.manual(record_property, ${pq(b.text)})  # not automated: check by hand or rephrase in the sheet`);
              }
              continue;
            }
            body.push(`    with ui.step(${pq(`预期 ${b.no}: ${b.text}`)}):`);
            for (const line of code) body.push("        " + line);
          }
        }
        if (!body.length) body.push("    pass");
        L.push(...body);
      }
    }
  }
  L.push("");
  return { source: L.join("\n"), map, stats: { ...stats, tags: [...stats.tags] } };
}

export function runtimePy(cfg) {
  return RUNTIME_PY.replace("__ROUTES__", JSON.stringify(cfg.routes || {}, null, 4).replace(/\n/g, "\n"));
}

export function conftestPy(tags = []) {
  return CONFTEST_PY.replace("__TAGS__", JSON.stringify([...new Set(tags)]));
}
