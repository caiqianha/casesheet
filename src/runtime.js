// Source of the helper module written next to the generated specs.
// Written as TypeScript; `toJs()` strips the few annotations used here.

export const RUNTIME_TS = String.raw`// Generated by casesheet. Safe to regenerate; put project-specific tweaks in casesheet.config.json.
import { expect, test, type Locator, type Page } from '@playwright/test';

type Role = Parameters<Page['getByRole']>[0];

export const routes: Record<string, string> = __ROUTES__;

const norm = (s: string): string => s.trim().replace(/\s*(页面|页|page|screen)$/i, '').toLowerCase();
const esc = (s: string): string => s.replace(/[.*+?^$\u007B}()|[\]\\]/g, '\\$&');

async function resolve(cands: Locator[], timeout = 10000): Promise<Locator> {
  const union = cands.reduce((a, b) => a.or(b));
  try {
    await union.first().waitFor({ state: 'attached', timeout });
  } catch {
    // fall through: the action below will produce Playwright's own error message
  }
  for (const c of cands) if (await c.filter({ visible: true }).count()) return c.filter({ visible: true }).first();
  for (const c of cands) if (await c.count()) return c.first();
  return union.first();
}

export const ui = {
  /** Path for a page name from casesheet.config.json → routes. */
  route(name: string): string {
    const hit = Object.entries(routes).find(([k]) => k === name) || Object.entries(routes).find(([k]) => norm(k) === norm(name));
    if (!hit) throw new Error('casesheet: no route for "' + name + '". Add it to casesheet.config.json, e.g. { "routes": { "' + name + '": "/path" } }');
    return hit[1];
  },

  /** "打开 个人中心": a configured route is navigated to, otherwise a link / menu item with that name is clicked. */
  async open(page: Page, name: string): Promise<void> {
    const hit = Object.entries(routes).find(([k]) => k === name) || Object.entries(routes).find(([k]) => norm(k) === norm(name));
    if (hit) {
      await page.goto(hit[1]);
      return;
    }
    const cands = ui.anyCandidates(page, name);
    const union = cands.reduce((a, b) => a.or(b));
    try {
      await union.first().waitFor({ state: 'attached', timeout: 5000 });
    } catch {
      throw new Error('casesheet: "' + name + '" is neither a route in casesheet.config.json nor a visible link/button on the page. Add { "routes": { "' + name + '": "/path" } } or rephrase the step.');
    }
    await (await resolve(cands)).click();
  },

  url(target: string, mode: 'url' | 'contains' | 'route'): RegExp | string {
    if (mode === 'route') return ui.url(ui.route(target), 'url');
    if (mode === 'contains') return new RegExp(esc(target));
    if (/^https?:\/\//i.test(target)) return target;
    return new RegExp('^[a-z]+://[^/]+' + esc(target.replace(/\/$/, '')) + '/?(?:[?#]|$)');
  },

  env(name: string): string {
    const v = process.env[name];
    if (v === undefined) throw new Error('casesheet: environment variable ' + name + ' is not set (used as {{' + name + '}} in the sheet)');
    return v;
  },

  fieldCandidates(page: Page, name: string): Locator[] {
    return [
      page.getByLabel(name, { exact: true }),
      page.getByPlaceholder(name, { exact: true }),
      page.getByRole('textbox', { name, exact: true }),
      page.locator('[name="' + name + '"], [id="' + name + '"]'),
      page.getByLabel(name),
      page.getByPlaceholder(name),
      page.getByRole('textbox', { name }),
      page.getByRole('combobox', { name }),
      page.locator('label', { hasText: name }).locator('input, textarea, select'),
      page.locator('label', { hasText: name }).locator('..').locator('input, textarea, select'),
    ];
  },

  /** Best matching form control for a label / placeholder / name, in priority order (not DOM order). */
  async pickField(page: Page, name: string): Promise<Locator> {
    return resolve(ui.fieldCandidates(page, name));
  },

  async fill(page: Page, name: string, value: string): Promise<void> {
    const el = await ui.pickField(page, name);
    await el.fill(value);
  },

  anyCandidates(page: Page, name: string, kind?: Role | null): Locator[] {
    if (kind) return [page.getByRole(kind, { name, exact: true }), page.getByRole(kind, { name })];
    return [
      page.getByRole('button', { name, exact: true }),
      page.getByRole('link', { name, exact: true }),
      page.getByRole('menuitem', { name, exact: true }),
      page.getByRole('tab', { name, exact: true }),
      page.getByRole('option', { name, exact: true }),
      page.getByLabel(name, { exact: true }),
      page.getByText(name, { exact: true }),
      page.getByRole('button', { name }),
      page.getByRole('link', { name }),
      page.getByTitle(name),
      page.getByText(name),
    ];
  },

  /** Best matching clickable / named element, buttons and links before plain text. */
  async pickAny(page: Page, name: string, kind?: Role | null): Promise<Locator> {
    return resolve(ui.anyCandidates(page, name, kind));
  },

  async click(page: Page, name: string, kind?: Role | null, opts?: { button?: 'left' | 'right' | 'middle'; clickCount?: number }): Promise<void> {
    const el = await ui.pickAny(page, name, kind);
    await el.click(opts);
  },

  /** Visible text anywhere on the page (toast, alert, label, cell). */
  text(page: Page, text: string, kind?: Role | null): Locator {
    if (kind) return page.getByRole(kind, { name: text, exact: true }).or(page.getByRole(kind, { name: text })).filter({ visible: true }).first();
    return page.getByText(text, { exact: true }).or(page.getByText(text)).or(page.getByRole('alert').filter({ hasText: text })).filter({ visible: true }).first();
  },

  /** Every match, visible or not: used for "must not be visible" checks. */
  textAll(page: Page, text: string, kind?: Role | null): Locator {
    if (kind) return page.getByRole(kind, { name: text, exact: true }).filter({ visible: true });
    return page.getByText(text).filter({ visible: true });
  },

  async select(page: Page, field: string, option: string): Promise<void> {
    const el = await resolve(ui.fieldCandidates(page, field).concat(ui.anyCandidates(page, field)));
    const tag = await el.evaluate((n) => n.tagName.toLowerCase()).catch(() => '');
    if (tag === 'select') {
      await el.selectOption({ label: option });
      return;
    }
    await el.click();
    const opt = page.getByRole('option', { name: option, exact: true }).or(page.getByRole('option', { name: option })).or(page.getByText(option, { exact: true })).filter({ visible: true }).first();
    await opt.click();
  },

  checkCandidates(page: Page, label: string): Locator[] {
    return [
      page.getByRole('checkbox', { name: label, exact: true }),
      page.getByRole('radio', { name: label, exact: true }),
      page.getByRole('switch', { name: label, exact: true }),
      page.getByRole('checkbox', { name: label }),
      page.getByRole('radio', { name: label }),
      page.getByRole('switch', { name: label }),
      page.getByLabel(label, { exact: true }),
      page.getByLabel(label),
    ];
  },

  async pickCheck(page: Page, label: string): Promise<Locator> {
    return resolve(ui.checkCandidates(page, label));
  },

  async check(page: Page, label: string, checked: boolean): Promise<void> {
    const el = await ui.pickCheck(page, label);
    await el.setChecked(checked);
  },

  async upload(page: Page, field: string | null, file: string): Promise<void> {
    const input = field ? await resolve(ui.fieldCandidates(page, field).concat(page.locator('input[type=file]'))) : page.locator('input[type=file]').first();
    await input.setInputFiles(file);
  },

  async closeDialog(page: Page): Promise<void> {
    const dialog = page.getByRole('dialog').filter({ visible: true }).last();
    const btn = dialog.getByRole('button', { name: /^(关闭|取消|确定|知道了|close|cancel|ok|dismiss|×|✕)$/i }).or(dialog.getByLabel(/close|关闭/i)).filter({ visible: true }).first();
    if (await btn.count()) await btn.click();
    else await page.keyboard.press('Escape');
  },

  /** Expectation casesheet could not turn into code: recorded on the report, does not fail the test. */
  manual(text: string): void {
    test.info().annotations.push({ type: 'manual check', description: text });
  },

  expect,
};
`;

export function toJs(ts) {
  return ts
    .replace("import { expect, test, type Locator, type Page } from '@playwright/test';", "import { expect, test } from '@playwright/test';")
    .replace(/^type Role = .*\n/m, "")
    .replace(/: Record<string, string> =/g, " =")
    .replace(/: Promise<void>/g, "")
    .replace(/: Promise<Locator>/g, "")
    .replace(/: RegExp \| string/g, "")
    .replace(/: Locator\[\]/g, "")
    .replace(/: Locator\b/g, "")
    .replace(/: Page\b/g, "")
    .replace(/\?: Role \| null/g, "")
    .replace(/: 'url' \| 'contains' \| 'route'/g, "")
    .replace(/: string \| null/g, "")
    .replace(/: boolean\b/g, "")
    .replace(/: void\b/g, "")
    .replace(/: string\b/g, "")
    .replace(/\?: \{ button\?: 'left' \| 'right' \| 'middle'; clickCount\?: number \}/g, "")
    .replace(/, timeout = 10000\)/g, ", timeout = 10000)");
}
