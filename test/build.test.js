import { test } from "node:test";
import assert from "node:assert/strict";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { execFileSync } from "node:child_process";
import { lit, emitSpec, analyzeCase } from "../src/emit.js";
import { loadConfig, expandMacros } from "../src/config.js";
import { toJs, RUNTIME_TS } from "../src/runtime.js";
import { parseMarkdown } from "../src/readers/markdown.js";
import { tablesToCases } from "../src/cases.js";

const root = path.join(path.dirname(new URL(import.meta.url).pathname), "..");
const bin = path.join(root, "bin", "casesheet.js");
const run = (args, opts = {}) => {
  try {
    return { code: 0, out: execFileSync("node", [bin, ...args], { encoding: "utf8", stdio: ["ignore", "pipe", "pipe"], ...opts }) };
  } catch (e) {
    return { code: e.status, out: (e.stdout || "") + (e.stderr || "") };
  }
};

test("lit: plain strings and {{ENV}} placeholders", () => {
  assert.equal(lit("admin"), "'admin'");
  assert.equal(lit("it's"), "'it\\'s'");
  assert.equal(lit("{{USER}}"), "`${ui.env('USER')}`");
  assert.equal(lit("user-{{ID}}@x.com"), "`user-${ui.env('ID')}@x.com`");
});

test("macros expand once with sub numbering and inherit expectations", () => {
  const steps = [{ text: "登录系统", expected: ["看到 首页"] }, { text: "点击 A", expected: [] }];
  const out = expandMacros(steps, { 登录系统: ["打开 /login", "点击 登录"] });
  assert.deepEqual(out.map((s) => [s.text, s.macro, s.sub, s.expected]), [["打开 /login", "登录系统", 1, []], ["点击 登录", "登录系统", 2, ["看到 首页"]], ["点击 A", undefined, undefined, []]]);
});

test("emitSpec: structure, tags, annotations, fixme and manual markers", () => {
  const md = `# 登录\n\n| 编号 | 标题 | 优先级 | 标签 | 前置条件 | 步骤 | 预期 |\n|---|---|---|---|---|---|---|\n| T1 | 登录 | P0 | smoke | 已有账号 | 1. 打开 登录页<br>2. 输入 用户名 {{U}}<br>3. 点击 登录 | 跳转到首页<br>登录成功 |\n| T2 | 怪步骤 | | | | 做点什么 | 显示 ok |\n`;
  const cases = tablesToCases(parseMarkdown(md).tables, "t.md");
  const cfg = { ...loadConfig(null, os.tmpdir()), routes: { 登录页: "/login" } };
  const { source, map, stats } = emitSpec(cases, cfg, { sourceRel: "t.md" });
  assert.match(source, /^\/\/ Generated by casesheet from t\.md/);
  assert.match(source, /import \{ ui \} from '\.\/_casesheet';/);
  assert.match(source, /test\.describe\('登录', \(\) => \{/);
  assert.match(source, /test\('\[T1\] 登录', \{ tag: \['@P0', '@smoke'\], annotation: \[\{ type: 'source', description: 't\.md:5' \}\] \}/);
  assert.match(source, /\/\/ 前置条件 \/ precondition: 已有账号/);
  assert.match(source, /await page\.goto\('\/login'\);/, "known route becomes a literal");
  const open = emitSpec(tablesToCases(parseMarkdown("| 步骤 |\n|---|\n| 进入 个人中心 |\n").tables, "o.md"), cfg, { sourceRel: "o.md" });
  assert.match(open.source, /await ui\.open\(page, '个人中心'\);/, "unknown page name falls back to ui.open");
  assert.match(source, /await ui\.fill\(page, '用户名', `\$\{ui\.env\('U'\)\}`\);/);
  assert.match(source, /toHaveURL\(ui\.url\('首页', 'route'\)\)/, "unknown route resolved at runtime");
  assert.match(source, /ui\.manual\('登录成功'\);/);
  assert.match(source, /test\.fixme\(true, 'unrecognized step: 做点什么'\);/);
  assert.equal(stats.cases, 2);
  assert.equal(stats.fixme, 1);
  assert.equal(stats.manual, 1);
  assert.deepEqual(map.map((m) => m.id), ["T1", "T2"]);
  const strict = emitSpec(cases, { ...cfg, strict: true }, { sourceRel: "t.md" });
  assert.match(strict.source, /test\.fixme\(true, 'unrecognized expectation: 登录成功'\);/);
});

test("analyzeCase reports unknown steps and expectations", () => {
  const c = { preconditions: ["已登录"], steps: [{ text: "登录系统", expected: ["登录成功", "显示 首页"] }, { text: "点击 A", expected: [] }] };
  const a = analyzeCase(c, { macros: {} });
  assert.deepEqual(a.unknownSteps, ["登录系统"]);
  assert.deepEqual(a.unknownExpect, ["登录成功"]);
  assert.equal(a.stepCount, 2);
});

test("runtime: TS → JS strip leaves valid JavaScript", () => {
  const js = toJs(RUNTIME_TS.replace("__ROUTES__", "{}"));
  assert.doesNotMatch(js, /: (Page|Locator|string|Role|Promise|boolean|void)\b/);
  const f = path.join(fs.mkdtempSync(path.join(os.tmpdir(), "cs-rt-")), "rt.mjs");
  fs.writeFileSync(f, js.replace(/^import .*$/m, "const expect = 0, test = 0;"));
  execFileSync("node", ["--check", f]);
});

test("cli: build example sheets in ts and js, check exit codes, grammar, init", () => {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), "cs-cli-"));
  const ex = path.join(root, "examples");
  let r = run(["build", "login.md", "-o", path.join(dir, "ts")], { cwd: ex });
  assert.equal(r.code, 0, r.out);
  assert.match(r.out, /7 cases, 30 steps/);
  assert.match(r.out, /\[TC-011\] 确认退出/);
  const spec = fs.readFileSync(path.join(dir, "ts", "login.spec.ts"), "utf8");
  assert.match(spec, /\/\/ macro: 登录系统/);
  assert.match(spec, /test\.step\('1\.1\. 打开 登录页'/, "macro steps keep the sheet's step number");
  assert.ok(fs.existsSync(path.join(dir, "ts", "_casesheet.ts")));
  const map = JSON.parse(fs.readFileSync(path.join(dir, "ts", "casesheet.map.json"), "utf8"));
  assert.equal(map.cases.length, 7);
  assert.match(map.cases[0].spec, /login\.spec\.ts:\d+$/);

  r = run(["build", "login.xlsx", "login.en.csv", "-o", path.join(dir, "js"), "--js", "--quiet"], { cwd: ex });
  assert.equal(r.code, 0, r.out);
  assert.ok(fs.existsSync(path.join(dir, "js", "login.spec.js")));
  assert.ok(fs.existsSync(path.join(dir, "js", "login.en.spec.js")));
  assert.ok(fs.existsSync(path.join(dir, "js", "_casesheet.js")));
  for (const f of ["login.spec.js", "login.en.spec.js", "_casesheet.js"]) {
    const m = path.join(dir, "js", f + ".mjs");
    fs.copyFileSync(path.join(dir, "js", f), m);
    execFileSync("node", ["--check", m]);
  }

  r = run(["build", "login.md", "-o", path.join(dir, "split"), "--split", "module", "--quiet"], { cwd: ex });
  assert.equal(r.code, 0, r.out);
  assert.ok(fs.existsSync(path.join(dir, "split", "登录模块.spec.ts")));
  assert.ok(fs.existsSync(path.join(dir, "split", "个人中心.spec.ts")));

  r = run(["check", "login.md"], { cwd: ex });
  assert.equal(r.code, 1, "unknown step fails check");
  assert.match(r.out, /29\/30 steps recognised/);
  r = run(["check", "login.en.csv", "--quiet"], { cwd: ex });
  assert.equal(r.code, 1);
  assert.match(r.out, /sign in/);

  r = run(["grammar"]);
  assert.equal(r.code, 0);
  assert.match(r.out, /点击 登录 按钮/);
  r = run(["grammar", "--json"]);
  assert.ok(JSON.parse(r.out).length >= 30);

  r = run(["init", path.join(dir, "proj")]);
  assert.equal(r.code, 0, r.out);
  assert.ok(fs.existsSync(path.join(dir, "proj", "cases", "example.md")));
  assert.ok(fs.existsSync(path.join(dir, "proj", "casesheet.config.json")));
  r = run(["init", path.join(dir, "proj")]);
  assert.match(r.out, /kept existing/);

  r = run(["build"]);
  assert.equal(r.code, 1);
  assert.match(r.out, /at least one sheet/);
  r = run(["nope"]);
  assert.match(r.out, /unknown command/);
  r = run(["--version"]);
  assert.match(r.out, /^\d+\.\d+\.\d+/);
});

test("config: validation errors are specific", () => {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), "cs-cfg-"));
  fs.writeFileSync(path.join(dir, "casesheet.config.json"), JSON.stringify({ outt: "x" }));
  assert.throws(() => loadConfig(null, dir), /unknown option "outt"/);
  fs.writeFileSync(path.join(dir, "casesheet.config.json"), JSON.stringify({ macros: { a: "not-array" } }));
  assert.throws(() => loadConfig(null, dir), /macro "a" must be an array/);
  assert.throws(() => loadConfig("missing.json", dir), /not found/);
});
