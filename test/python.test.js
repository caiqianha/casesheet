test("pylit / pyIdent", () => {
  assert.equal(pylit("admin"), '"admin"');
  assert.equal(pylit('say "hi"\n{x}'), '"say \\"hi\\"\\n{x}"');
  assert.equal(pylit("{{USER}}"), "f\"{ui.env('USER')}\"");
  assert.equal(pylit("u-{{ID}}@{x}"), "f\"u-{ui.env('ID')}@{{x}}\"");
  assert.equal(pyIdent("TC-001"), "tc_001");
  assert.equal(pyIdent("正确账号密码登录成功"), "正确账号密码登录成功");
  assert.equal(pyIdent("Login with valid credentials!"), "login_with_valid_credentials");
  assert.equal(pyIdent("123"), "_123");
  assert.equal(pyIdent("P0", { lower: false }), "P0");
  assert.equal(pyIdent("smoke test", { lower: false }), "smoke_test");
  assert.equal(pyIdent("--"), "x");
  assert.equal(specFileName("/x/login.en.csv", { lang: "py" }), "test_login_en.py");
  assert.equal(specFileName("/x/login.md", { lang: "py" }, "登录模块"), "test_登录模块.py");
  assert.equal(specFileName("/x/login.md", { lang: "py" }, "2fa"), "test__2fa.py");
});

test("emitSpecPy: structure, markers, steps, fixme / manual / strict", () => {
  const cfg = { ...loadConfig(path.join(ex, "casesheet.config.json")), lang: "py" };
  const cases = tablesToCases(parseMarkdown(fs.readFileSync(path.join(ex, "login.md"), "utf8")).tables, "login.md");
  const { source, map, stats } = emitSpecPy(cases, cfg, { sourceRel: "login.md" });
  assert.match(source, /^# Generated by casesheet from login\.md/);
  assert.match(source, /from playwright\.sync_api import Page, expect\n\nfrom _casesheet import ui/);
  assert.match(source, /# ---- 登录模块 ----/);
  assert.match(source, /@pytest\.mark\.P0\n@pytest\.mark\.casesheet\(id="TC-001", title="\[TC-001\] 正确账号密码登录成功", module="登录模块", source="login\.md:5"\)\ndef test_tc_001_正确账号密码登录成功\(page: Page, record_property\):\n    """\[TC-001\] 正确账号密码登录成功"""\n    # 前置条件 \/ precondition: 已有账号 admin \/ 123456\n    with ui\.step\("1\. 打开 \/login"\):\n        page\.goto\("\/login"\)/);
  assert.match(source, /ui\.fill\(page, "用户名", "admin"\)/);
  assert.match(source, /ui\.click\(page, "登录", "button"\)/);
  assert.match(source, /expect\(page\)\.to_have_url\(ui\.url\("\/dashboard", "url"\)\)/);
  assert.match(source, /expect\(ui\.text\(page, "欢迎回来, admin"\)\)\.to_be_visible\(\)/);
  assert.match(source, /page\.keyboard\.press\("Enter"\)/);
  assert.match(source, /expect\(ui\.pick_any\(page, "登录", "button"\)\)\.to_be_disabled\(\)/);
  assert.match(source, /expect\(ui\.pick_check\(page, "记住我"\)\)\.not_to_be_checked\(\)/);
  assert.match(source, /expect\(page\)\.to_have_title\(re\.compile\(re\.escape\("登录"\)\)\)/);
  assert.match(source, /ui\.fill\(page, "用户名", f"\{ui\.env\('CASESHEET_USER'\)\}"\)/);
  assert.match(source, /expect\(ui\.text_all\(page, "登录", "button"\)\)\.to_have_count\(0\)/);
  assert.match(source, /# macro: 登录系统\n    with ui\.step\("1\.1\. 打开 登录页"\):\n        page\.goto\("\/login"\)/);
  assert.match(source, /expect\(ui\.pick_field\(page, "昵称"\)\)\.to_have_value\("才浅"\)/);
  assert.match(source, /ui\.fixme\(record_property, "unrecognized step: 确认退出"\)/);
  assert.equal(stats.cases, 7);
  assert.equal(stats.fixme, 1);
  assert.deepEqual(stats.tags, ["P0", "P1", "P2"]);
  assert.deepEqual(map.map((m) => m.id), ["TC-001", "TC-002", "TC-003", "TC-004", "TC-005", "TC-010", "TC-011"]);
  assert.equal(source.split("\n")[map[0].line - 1], "def test_tc_001_正确账号密码登录成功(page: Page, record_property):");
  const strict = emitSpecPy(cases, { ...cfg, strict: true }, { sourceRel: "login.md" });
  assert.match(strict.source, /pytest\.fail\("unrecognized step: 确认退出"\)/);
  const manual = emitSpecPy(tablesToCases(parseMarkdown("| 步骤 | 预期 |\n|---|---|\n| 打开 /a | 登录成功 |\n").tables, "m.md"), cfg, { sourceRel: "m.md" });
  assert.match(manual.source, /ui\.manual\(record_property, "登录成功"\)  # not automated/);
  assert.match(emitSpecPy(tablesToCases(parseMarkdown("| 步骤 | 预期 |\n|---|---|\n| 打开 /a | 登录成功 |\n").tables, "m.md"), { ...cfg, strict: true }, { sourceRel: "m.md" }).source, /pytest\.fail\("unrecognized expectation: 登录成功"\)/);
  const dup = emitSpecPy(tablesToCases(parseMarkdown("| 标题 | 步骤 |\n|---|---|\n| 同名 | 打开 /a |\n| 同名 | 打开 /b |\n").tables, "m.md"), cfg, { sourceRel: "m.md" });
  assert.match(dup.source, /def test_r003_同名\(/);
  assert.match(dup.source, /def test_r004_同名\(/);
  assert.match(runtimePy(cfg), /ROUTES = \{\n    "登录页": "\/login",\n    "首页": "\/dashboard"\n\}/);
  assert.match(conftestPy(["P0", "smoke"]), /TAGS = \["P0","smoke"\]/);
});

test("cli build --lang py writes specs, _casesheet.py, conftest.py and the map", { skip: false }, () => {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), "cs-py-"));
  const out = execFileSync("node", [bin, "build", "login.md", "login.en.csv", "--lang", "py", "-o", dir], { cwd: ex, encoding: "utf8" });
  assert.match(out, /12 cases, 45 steps → .* \(test_login\.py, test_login_en\.py, _casesheet\.py, conftest\.py, casesheet\.map\.json\)/);
  assert.match(out, /next: pytest .* --base-url/);
  const map = JSON.parse(fs.readFileSync(path.join(dir, "casesheet.map.json"), "utf8"));
  assert.match(map.cases[0].spec, /test_login\.py:\d+$/);
  const rt = fs.readFileSync(path.join(dir, "_casesheet.py"), "utf8");
  for (const fn of ["def resolve(", "def open(", "def url(", "def fill(", "def click(", "def text(", "def text_all(", "def select(", "def check(", "def upload(", "def close_dialog(", "def manual(", "def env("]) assert.ok(rt.includes(fn), fn);
  assert.match(fs.readFileSync(path.join(dir, "conftest.py"), "utf8"), /def pytest_sessionfinish/);
  const split = fs.mkdtempSync(path.join(os.tmpdir(), "cs-py-"));
  execFileSync("node", [bin, "build", "login.md", "--lang", "py", "--split", "module", "-o", split, "--quiet"], { cwd: ex });
  assert.ok(fs.existsSync(path.join(split, "test_登录模块.py")));
  assert.ok(fs.existsSync(path.join(split, "test_个人中心.py")));
});

test("generated Python compiles (python3 -m py_compile)", { skip: hasPython ? false : `${python} not found` }, () => {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), "cs-pyc-"));
  execFileSync("node", [bin, "build", "login.md", "login.en.csv", "--lang", "py", "-o", dir, "--quiet"], { cwd: ex });
  const md = "| 编号 | 步骤 | 预期 | 数据 |\n|---|---|---|---|\n| T1 | 1. 打开 /a<br>2. 输入 用户名 {{user}}<br>3. 双击 文件<br>4. 右键点击 文件<br>5. 上传 a.png<br>6. 等待 1 秒<br>7. 截图<br>8. 滚动到底部<br>9. 在 城市 中选择 北京<br>10. 审批通过 单号 \"x\" | 显示 ok<br>标题为 a.b*c<br>登录成功 | user=a<br>user=b |\n";
  fs.writeFileSync(path.join(dir, "all.md"), md);
  execFileSync("node", [bin, "build", path.join(dir, "all.md"), "--lang", "py", "-o", dir, "--quiet", "--config", path.join(ex, "casesheet.config.json")], { cwd: ex });
  const files = fs.readdirSync(dir).filter((f) => f.endsWith(".py")).map((f) => path.join(dir, f));
  assert.ok(files.length >= 5, files.join());
  execFileSync(python, ["-m", "py_compile", ...files], { stdio: "pipe" });
});
